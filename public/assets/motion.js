// CiteReady motion: scroll reveals, counters, meters, the looping hero demo, scroll-linked progress.
// Everything degrades to static, visible content (no JS, reduced motion, or GSAP blocked).
(function () {
  const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const ease = (t) => 1 - Math.pow(1 - t, 3);

  function tween(ms, fn, done) {
    if (reduce) { fn(1); if (done) done(); return; }
    const start = performance.now();
    const step = (now) => {
      const t = Math.min(1, (now - start) / ms);
      fn(ease(t));
      if (t < 1) requestAnimationFrame(step); else if (done) done();
    };
    requestAnimationFrame(step);
  }

  function onVisible(els, cb, margin) {
    if (reduce || !("IntersectionObserver" in window)) { els.forEach(cb); return; }
    const io = new IntersectionObserver((entries) => {
      entries.forEach((e) => { if (e.isIntersecting) { cb(e.target); io.unobserve(e.target); } });
    }, { rootMargin: margin || "0px 0px -10% 0px" });
    els.forEach((el) => io.observe(el));
  }

  // Reveal on scroll
  onVisible(document.querySelectorAll(".reveal"), (el) => el.classList.add("in"));

  // Count-up numbers: <span data-count="94" data-suffix="%">
  onVisible(document.querySelectorAll("[data-count]"), (el) => {
    const to = Number(el.dataset.count), from = Number(el.dataset.from || 0), suf = el.dataset.suffix || "";
    tween(1300, (t) => { el.textContent = Math.round(from + (to - from) * t) + suf; });
  });

  // Meters: <div class="meter" data-meter="72"><i></i></div>
  onVisible(document.querySelectorAll("[data-meter]"), (el) => { el.style.setProperty("--w", el.dataset.meter + "%"); });

  // ---------------------------------------------------------------- hero demo loop: audit → fix → re-audit
  const mock = document.getElementById("mock");
  if (mock) {
    const ring = mock.querySelector(".arc");
    const num = mock.querySelector("[data-score]");
    const label = mock.querySelector("[data-phase]");
    const rows = Array.from(mock.querySelectorAll(".row"));
    const fix = mock.querySelector(".mock-fix code");
    const badge = mock.parentElement.querySelector(".float-badge.b1");
    const C = 2 * Math.PI * 52;
    let score = 0;
    const setScore = (s, color) => {
      ring.style.stroke = color;
      ring.style.strokeDashoffset = String(C * (1 - s / 100));
      num.textContent = String(Math.round(s));
    };
    const fixLines = [
      '<span class="c"># Generated by CiteReady for yourclient.com</span>',
      '<span class="k">User-agent:</span> OAI-SearchBot',
      '<span class="k">User-agent:</span> PerplexityBot',
      '<span class="k">User-agent:</span> Claude-SearchBot',
      '<span class="k">Allow:</span> /',
      '<span class="k">Sitemap:</span> <span class="s">https://yourclient.com/sitemap.xml</span>',
    ];
    const typeFix = (done) => {
      if (reduce) { fix.innerHTML = fixLines.join("\n"); done(); return; }
      fix.innerHTML = "";
      let i = 0;
      const next = () => {
        if (i >= fixLines.length) { done(); return; }
        fix.innerHTML += (i ? "\n" : "") + fixLines[i++];
        setTimeout(next, 260);
      };
      next();
    };
    const animateTo = (target, color, ms, done) => {
      const from = score;
      tween(ms, (t) => { score = from + (target - from) * t; setScore(score, color); }, done);
    };
    const paint = (r, state) => {
      const before = state === "before";
      r.classList.remove("ok", "bad", "mid");
      r.classList.add(before ? r.dataset.before : "ok");
      r.querySelector(".ic").textContent = before ? (r.dataset.before === "mid" ? "!" : "✕") : "✓";
      r.querySelector("span").textContent = before ? r.dataset.bad : r.dataset.good;
      r.querySelector("b").textContent = before ? r.dataset.ptsBefore : r.dataset.ptsAfter;
    };
    const stagger = (state, done) => {
      if (reduce) { rows.forEach((r) => paint(r, state)); if (done) done(); return; }
      rows.forEach((r, i) => setTimeout(() => {
        r.animate([{ opacity: 0.2, transform: "translateX(-8px)" }, { opacity: 1, transform: "none" }], { duration: 420, easing: "cubic-bezier(.22,1,.36,1)" });
        paint(r, state);
        if (i === rows.length - 1 && done) setTimeout(done, 320);
      }, i * 320));
    };
    const cycle = () => {
      label.textContent = "Auditing yourclient.com…";
      if (badge) badge.style.opacity = "0";
      score = 0;
      setScore(0, "var(--fail)");
      fix.innerHTML = '<span class="c"># Waiting for results…</span>';
      stagger("before", () => animateTo(41, "var(--fail)", 1100, () => {
        label.textContent = "4 problems found · writing fixes";
        typeFix(() => setTimeout(() => {
          label.textContent = "Fixes applied · re-auditing";
          stagger("after", () => animateTo(94, "var(--pass)", 1300, () => {
            label.textContent = "AI-ready · +53 points";
            if (badge) {
              badge.style.opacity = "1";
              badge.animate([{ transform: "scale(.8)", opacity: 0 }, { transform: "scale(1)", opacity: 1 }], { duration: 450, easing: "cubic-bezier(.34,1.56,.64,1)" });
            }
            setTimeout(cycle, 4200);
          }));
        }, 900));
      }));
    };
    ring.style.strokeDasharray = String(C);
    if (reduce) {
      rows.forEach((r) => paint(r, "after"));
      setScore(94, "var(--pass)");
      label.textContent = "AI-ready · +53 points";
      typeFix(() => {});
    } else {
      onVisible([mock], () => setTimeout(cycle, 350), "0px");
    }
  }

  // ---------------------------------------------------------------- GSAP extras (optional enhancement)
  window.addEventListener("load", () => {
    const g = window.gsap, ST = window.ScrollTrigger;
    if (!g || !ST || reduce) return;
    g.registerPlugin(ST);
    document.querySelectorAll(".progress-line i").forEach((bar) => {
      g.fromTo(bar, { scaleX: 0 }, { scaleX: 1, ease: "none", scrollTrigger: { trigger: bar.closest(".steps"), start: "top 75%", end: "bottom 55%", scrub: 0.8 } });
    });
    document.querySelectorAll("[data-stagger]").forEach((grid) => {
      g.from(grid.children, { opacity: 0, y: 22, scale: 0.97, duration: 0.5, stagger: { each: 0.07 }, ease: "power2.out", clearProps: "all", scrollTrigger: { trigger: grid, start: "top 88%" } });
    });
  });
})();
