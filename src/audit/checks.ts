function pageTypeTemplate(ctx: AuditContext, kind: ReturnType<typeof guessPageKind>): { code: string; label: string } {
  const name = siteName(ctx);
  const title = ctx.html.headings.find((h) => h.level === 1)?.text || ctx.html.title || name;
  const desc = trimTo(siteDescription(ctx), 300);
  const img = primaryImage(ctx);
  const org = { "@type": "Organization", name, url: `${ctx.origin}/` };
  const qs = ctx.html.headings.filter((h) => isQuestion(h.text)).slice(0, 5);
  switch (kind) {
    case "product":
      return {
        label: "Product",
        code: json({
          "@context": "https://schema.org",
          "@type": "Product",
          name: title,
          description: desc,
          image: img,
          brand: { "@type": "Brand", name },
          offers: {
            "@type": "Offer",
            url: ctx.finalUrl,
            price: "[price, e.g. 49.00]",
            priceCurrency: "[currency, e.g. USD]",
            availability: "https://schema.org/InStock",
          },
        }),
      };
    case "article":
      return {
        label: "Article",
        code: json({
          "@context": "https://schema.org",
          "@type": "Article",
          headline: trimTo(title, 110),
          description: desc,
          image: img,
          datePublished: ctx.html.meta["article:published_time"] || "[YYYY-MM-DD]",
          dateModified: ctx.html.meta["article:modified_time"] || new Date().toISOString().slice(0, 10),
          author: { "@type": "Person", name: ctx.html.meta["author"] || "[Author name]", url: `${ctx.origin}/about` },
          publisher: { ...org, logo: { "@type": "ImageObject", url: logoUrl(ctx) } },
          mainEntityOfPage: ctx.finalUrl,
        }),
      };
    case "local": {
      const tel = ctx.html.links.find((l) => l.href.startsWith("tel:"))?.href.slice(4) || "[phone]";
      return {
        label: "LocalBusiness",
        code: json({
          "@context": "https://schema.org",
          "@type": "LocalBusiness",
          name,
          url: `${ctx.origin}/`,
          image: img,
          telephone: tel,
          address: {
            "@type": "PostalAddress",
            streetAddress: "[street]",
            addressLocality: "[city]",
            postalCode: "[postal code]",
            addressCountry: "[country code, e.g. IN]",
          },
          openingHours: "[e.g. Mo-Fr 09:00-18:00]",
          priceRange: "[e.g. $$]",
        }),
      };
    }
    case "software":
      return {
        label: "SoftwareApplication",
        code: json({
          "@context": "https://schema.org",
          "@type": "SoftwareApplication",
          name,
          description: desc,
          url: `${ctx.origin}/`,
          applicationCategory: "BusinessApplication",
          operatingSystem: "Web",
          offers: { "@type": "Offer", price: "[lowest price, e.g. 0]", priceCurrency: "USD" },
        }),
      };
    default:
      return {
        label: "FAQPage",
        code: json({
          "@context": "https://schema.org",
          "@type": "FAQPage",
          mainEntity: (qs.length
            ? qs.map((q) => q.text)
            : [`What does ${name} do?`, `Who is ${name} for?`, `How much does ${name} cost?`]
          ).map((q) => ({
            "@type": "Question",
            name: q,
            acceptedAnswer: { "@type": "Answer", text: "[The answer exactly as shown on the page]" },
          })),
        }),
      };
  }
}

