export const robotsSearchBots: CheckFn = (ctx) => {
  const base = {
    id: "robots-search-bots",
    group: "reach" as const,
    title: "AI search bots allowed in robots.txt",
    points: 12,
    why: "If robots.txt blocks a search bot, that AI engine can't index the page and won't cite it in answers.",
  };
  const r = ctx.robots;
  if (r.status >= 500 || (r.error && r.status === 0)) {
    return result(
      base,
      0,
      `robots.txt didn't load (${r.status || r.error}). Crawlers treat a failing robots.txt as "block everything".`,
      [`GET ${r.url} → ${r.status || r.error}`],
      {
        title: "Make robots.txt load reliably",
        steps: [
          "Make sure /robots.txt returns status 200 (or 404 if you don't want one). A 5xx error tells crawlers to stay away.",
          "If a firewall rule protects /robots.txt, exclude that path from challenges.",
          "Then upload the file below.",
        ],
        code: generateRobotsTxt(ctx),
        language: "robots",
        where: "robots.txt at the root of your site",
      },
    );
  }
  if (!r.present) {
    return result(base, base.points, "No robots.txt found, so every crawler is allowed by default.", [
      `GET ${r.url} → ${r.status}${r.status === 200 ? " (not a robots.txt file)" : ""}`,
      "With no robots.txt, nothing is blocked.",
    ]);
  }
  const path = pagePath(ctx);
  const per = base.points / SCORED_SEARCH_BOTS.length;
  let earned = 0;
  const blocked: string[] = [];
  const evidence: string[] = [];
  for (const token of SCORED_SEARCH_BOTS) {
    const d = isAllowed(r.parsed, token, path);
    if (d.allowed) {
      earned += per;
      evidence.push(`✓ ${token}: allowed${d.matchedAgent ? ` (group "${d.matchedAgent}")` : ""}`);
    } else {
      blocked.push(token);
      evidence.push(`✗ ${token}: blocked by line ${d.rule?.line} "Disallow: ${d.rule?.path}" in group "${d.matchedAgent}"`);
    }
  }
  if (!blocked.length) return result(base, earned, "All 6 AI search bots can crawl this page.", evidence);
  return result(base, earned, `${blocked.length} of 6 AI search bots are blocked: ${blocked.join(", ")}.`, evidence, {
    title: "Replace your robots.txt with this corrected version",
    steps: [
      "This keeps your existing rules for other crawlers and your private paths, and explicitly allows AI search bots.",
      "Training bots keep whatever setting you chose. That's a business decision and doesn't affect AI search.",
      "Upload it to the root of your site, then re-run this audit.",
    ],
    code: generateRobotsTxt(ctx),
    language: "robots",
    where: "robots.txt at the root of your site",
  });
};

/** Build a corrected robots.txt that preserves existing rules and allows AI search bots. */
export function generateRobotsTxt(ctx: AuditContext): string {
  const parsed: ParsedRobots = ctx.robots.present ? ctx.robots.parsed : { groups: [], sitemaps: [] };
  const searchTokens = BOTS.filter((b) => b.kind !== "training").map((b) => b.token);
  const searchLower = new Set(searchTokens.map((t) => t.toLowerCase()));
  const lines: string[] = [`# Generated by CiteReady for ${ctx.host}`, ""];

  // Private paths from the "*" group carry over to AI search bots (minus any full-site block).
  const starRules = parsed.groups
    .filter((g) => g.agents.includes("*"))
    .flatMap((g) => g.rules)
    .filter((r) => !(r.type === "disallow" && (r.path === "/" || r.path === "/*")) && r.path !== "");

  lines.push("# AI search and answer bots: allowed, so this site can appear in AI answers.");
  for (const t of searchTokens) lines.push(`User-agent: ${t}`);
  lines.push("Allow: /");
  for (const r of starRules) lines.push(`${r.type === "allow" ? "Allow" : "Disallow"}: ${r.path}`);
  lines.push("");

  // Training bots: keep existing choice.
  const trainingGroups = parsed.groups.filter((g) => g.agents.some((a) => getBot(a)?.kind === "training"));
  lines.push("# Training crawlers: your choice. Blocking them does not remove you from AI search.");
  if (trainingGroups.length) {
    for (const g of trainingGroups) {
      for (const a of g.agents) if (getBot(a)?.kind === "training") lines.push(`User-agent: ${getBot(a)!.token}`);
      for (const r of g.rules) lines.push(`${r.type === "allow" ? "Allow" : "Disallow"}: ${r.path}`);
      lines.push("");
    }
  } else {
    lines.push("# To opt out of AI training, uncomment the lines below:");
    lines.push("# User-agent: GPTBot");
    lines.push("# User-agent: ClaudeBot");
    lines.push("# User-agent: CCBot");
    lines.push("# User-agent: Google-Extended");
    lines.push("# Disallow: /");
    lines.push("");
  }

  // Everything else: keep existing groups (minus agents we now handle explicitly).
  const others = parsed.groups.filter((g) => g.agents.some((a) => !searchLower.has(a) && getBot(a)?.kind !== "training"));
  if (others.length) {
    lines.push("# Your existing rules for all other crawlers");
    for (const g of others) {
      const agents = g.agents.filter((a) => !searchLower.has(a) && getBot(a)?.kind !== "training");
      for (const a of agents) lines.push(`User-agent: ${a}`);
      if (!g.rules.length) lines.push("Disallow:");
      for (const r of g.rules) lines.push(`${r.type === "allow" ? "Allow" : "Disallow"}: ${r.path}`);
      lines.push("");
    }
  } else {
    lines.push("User-agent: *");
    lines.push("Allow: /");
    lines.push("");
  }

  const sitemaps = parsed.sitemaps.length ? parsed.sitemaps : [ctx.sitemap.valid ? ctx.sitemap.url : `${ctx.origin}/sitemap.xml`];
  for (const s of sitemaps) lines.push(`Sitemap: ${s}`);
  return lines.join("\n").trim() + "\n";
}

const CHALLENGE_MARKERS = [
  "cf-chl",
  "challenge-platform",
  "just a moment...",
  "attention required! | cloudflare",
  "cf-browser-verification",
  "px-captcha",
  "_incapsula_resource",
  "ddos-guard",
  "access denied",
  "request unsuccessful. incapsula",
  "verify you are human",
  "are you a robot",
];

export function looksLikeChallenge(body: string): boolean {
  const b = body.slice(0, 20000).toLowerCase();
  return CHALLENGE_MARKERS.some((m) => b.includes(m));
}

export const firewallTest: CheckFn = (ctx) => {
  const base = {
    id: "firewall-test",
    group: "reach" as const,
    title: "Firewall or CDN lets AI bots through",
    points: 10,
    why: "Firewalls and CDN bot protection can block AI crawlers even when robots.txt allows them. The owner usually never knows.",
  };
  const browserWords = ctx.html.wordCount;
  const evidence = [`Normal browser: status ${ctx.page.status}, ${browserWords} words`];
  if (!ctx.botFetches.length) {
    return result(base, base.points, "Live bot test was skipped.", evidence, undefined, "info");
  }
  const per = base.points / ctx.botFetches.length;
  let earned = 0;
  const blocked: string[] = [];
  for (const f of ctx.botFetches) {
    let problem = "";
    if (f.error) problem = f.error === "Timed out" ? "timed out" : "no response";
    else if ([401, 403, 406, 429, 451, 503].includes(f.status)) problem = `status ${f.status}`;
    else if (f.challenge) problem = "got a bot challenge page";
    else if (f.status >= 400) problem = `status ${f.status}`;
    else if (browserWords > 100 && f.words < browserWords * 0.3) problem = `much less content (${f.words} vs ${browserWords} words)`;
    if (problem) {
      blocked.push(f.token);
      evidence.push(`⚠ ${f.token}: ${problem}`);
    } else {
      earned += per;
      evidence.push(`✓ ${f.token}: status ${f.status}, ${f.words} words`);
    }
  }
  if (!blocked.length) return result(base, earned, "Our test requests using AI-bot user agents got the same page as a browser.", evidence);
  evidence.push(
    "Note: some firewalls verify real bots by IP address. Our test can be blocked while the real crawler gets through, so treat this as a possible block and confirm in your firewall logs.",
  );
  return result(
    base,
    earned,
    `Possible block: ${blocked.join(", ")} got a different response than a normal browser.`,
    evidence,
    { title: "Check your firewall and CDN bot settings", steps: firewallSteps(ctx) },
    "warn",
  );
};

