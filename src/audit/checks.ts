export const noindexCheck: CheckFn = (ctx) => {
  const base = {
    id: "noindex",
    group: "reach" as const,
    title: "No noindex or nosnippet",
    points: 4,
    why: "noindex removes the page from search indexes. nosnippet and max-snippet:0 stop engines from quoting your text in answers.",
  };
  const bad = /\b(noindex|none|nosnippet)\b|max-snippet\s*:\s*0\b/i;
  const findings: { where: string; value: string; line: string }[] = [];
  for (const name of ["robots", "googlebot", "bingbot", "googlebot-news"]) {
    const v = ctx.html.meta[name];
    if (v && bad.test(v)) findings.push({ where: `meta ${name}`, value: v, line: `<meta name="${name}" content="${escapeHtmlAttr(v)}">` });
  }
  const xr = ctx.page.headers["x-robots-tag"];
  if (xr && bad.test(xr)) findings.push({ where: "X-Robots-Tag header", value: xr, line: `X-Robots-Tag: ${xr}` });
  if (!findings.length) {
    return result(base, base.points, "No noindex or nosnippet directives found.", [
      `meta robots: ${ctx.html.meta["robots"] || "not set"}`,
      `X-Robots-Tag: ${xr || "not set"}`,
    ]);
  }
  return result(
    base,
    0,
    `This page tells search engines not to index or quote it (${findings.map((f) => f.value).join("; ")}).`,
    findings.map((f) => `${f.where}: ${f.value}`),
    {
      title: "Remove this line",
      steps: [
        findings.some((f) => f.where.startsWith("meta"))
          ? "Delete the meta tag below from the page's <head> (in WordPress, check Settings → Reading → \"Discourage search engines\" and your SEO plugin's page settings)."
          : "Remove the X-Robots-Tag header from your server or CDN config.",
        "If you only wanted to hide part of the page from snippets, use data-nosnippet on that element instead.",
      ],
      code: findings.map((f) => f.line).join("\n"),
      language: findings.some((f) => f.where.startsWith("meta")) ? "html" : "http",
      where: "Remove from your page",
    },
  );
};

export const sitemapCheck: CheckFn = (ctx) => {
  const base = {
    id: "sitemap",
    group: "reach" as const,
    title: "Sitemap exists and is listed in robots.txt",
    points: 4,
    why: "A sitemap tells crawlers which pages exist and when they changed, so new and updated pages get found faster.",
  };
  const s = ctx.sitemap;
  let earned = 0;
  const evidence: string[] = [];
  if (s.valid) {
    earned += 2;
    evidence.push(`✓ Sitemap found at ${s.url}`);
  } else evidence.push(`✗ No valid sitemap at ${s.url} (status ${s.status || "no response"})`);
  if (s.listedInRobots) {
    earned += 2;
    evidence.push("✓ robots.txt has a Sitemap: line");
  } else evidence.push("✗ robots.txt has no Sitemap: line");
  const summary =
    earned === 4 ? "Sitemap found and listed in robots.txt." : !s.valid ? "No sitemap found." : "Sitemap exists but robots.txt doesn't point to it.";
  const sitemapUrl = s.valid ? s.url : `${ctx.origin}/sitemap.xml`;
  return result(base, earned, summary, evidence, {
    title: s.valid ? "Add this line to robots.txt" : "Create a sitemap, then add this line to robots.txt",
    steps: s.valid
      ? ["Add the line below anywhere in robots.txt (usually at the end)."]
      : [
          sitemapHowTo(ctx),
          "Add the line below to robots.txt.",
          "Submit the sitemap in Google Search Console and Bing Webmaster Tools.",
        ],
    code: `Sitemap: ${sitemapUrl}`,
    language: "robots",
    where: "robots.txt",
  });
};

